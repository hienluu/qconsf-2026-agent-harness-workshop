"""Derive the bug_hunt workspace: the green reference, plus three bugs.

Same invariant as the refactor task: reference/ is ground truth (tests
green by construction); workspace/ is generated by applying exact,
documented substitutions. Edit the reference, re-run this script — never
hand-edit the workspace.

The three bugs interact by design:
  1. discounts.percent_off floors instead of rounding half-up — leaks into
     every discount AND (via tax.py's reuse) every tax amount.
  2. pricing taxes the pre-discount subtotal — invisible on carts with no
     discount, compounds with bug 1 everywhere else.
  3. receipt drops the empty-cart guard — a crash that tops the pytest
     output and has nothing to do with the arithmetic.

Usage: python scripts/derive_bug_hunt.py
"""

import shutil
from pathlib import Path

TASK_DIR = Path(__file__).resolve().parent.parent / "block2_naive_harness" / "tasks" / "medium" / "bug_hunt"
REFERENCE = TASK_DIR / "reference"
WORKSPACE = TASK_DIR / "workspace"

BUGS = [
    (
        "ordercalc/discounts.py",
        "return (cents * pct + 50) // 100",
        "return cents * pct // 100",
    ),
    (
        "ordercalc/pricing.py",
        "tax = tax_cents(taxable)",
        "tax = tax_cents(subtotal)",
    ),
    (
        "ordercalc/receipt.py",
        "average = cart.subtotal_cents() // count if count else 0",
        "average = cart.subtotal_cents() // count",
    ),
]


def main() -> None:
    if WORKSPACE.exists():
        shutil.rmtree(WORKSPACE)
    shutil.copytree(REFERENCE, WORKSPACE, ignore=shutil.ignore_patterns("__pycache__", ".pytest_cache"))

    for rel, clean, buggy in BUGS:
        path = WORKSPACE / rel
        text = path.read_text()
        assert clean in text, f"anchor not found in {rel}: {clean!r}"
        path.write_text(text.replace(clean, buggy))
    print(f"workspace derived at {WORKSPACE} with {len(BUGS)} bugs")


if __name__ == "__main__":
    main()
